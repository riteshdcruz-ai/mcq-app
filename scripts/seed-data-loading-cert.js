async function main() {
  if (!process.env.DATABASE_URL) {
    console.error("ERROR: DATABASE_URL is not set.");
    console.error('Run: $env:DATABASE_URL="file:..."; node scripts/seed-data-loading-cert.js');
    process.exit(1);
  }

  const admin = await prisma.user.findFirst({ where: { role: "admin" } });
  if (!admin) { console.error("ERROR: No admin user found."); process.exit(1); }

  let book = await prisma.book.findFirst({ where: { title: BOOK_TITLE } });
  if (!book) {
    book = await prisma.book.create({
      data: {
        title: BOOK_TITLE,
        filename: "Important Questions for Data Loadig Certifications.docx",
        filePath: "seeded",
        extractedText: "",
        uploadedById: admin.id,
      },
    });
    console.log(`Created book: "${book.title}"`);
  } else {
    console.log(`Reusing existing book: "${book.title}"`);
  }

  let inserted = 0, skipped = 0;
  for (const q of questions) {
    const exists = await prisma.question.findFirst({ where: { questionText: q.questionText } });
    if (exists) { skipped++; console.log(`  ~ Skipped (exists): ${q.questionText.substring(0, 70)}...`); continue; }
    await prisma.question.create({
      data: {
        bookId: book.id,
        questionText: q.questionText,
        optionA: q.optionA,
        optionB: q.optionB,
        optionC: q.optionC,
        optionD: q.optionD,
        correctOption: q.correctOption,
        explanation: q.explanation || "",
        difficulty: q.difficulty || "medium",
        aiGenerated: false,
        approved: true,
      },
    });
    inserted++;
    console.log(`  + ${q.questionText.substring(0, 75)}...`);
  }

  console.log(`\nDone — ${inserted} inserted, ${skipped} already existed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => prisma.$disconnect());
